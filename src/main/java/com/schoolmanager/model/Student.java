package com.schoolmanager.model;

public class Student {

    private int id;
    private String nombre;
    private String apellidoMaterno;
    private String apellidoPaterno;
    private int edad;
    private String curso;
    private String celular;
    private String nombrePadre;
    private String apellidoPadre;
    private String nombreMadre;
    private String apellidoMadre;
    private String celularPadre;
    private String celularMadre;

    public int getId() { return id; }
    public void setId(int id) { this.id = id; }

    public String getNombre() { return nombre; }
    public void setNombre(String nombre) { this.nombre = nombre; }

    public String getApellidoMaterno() { return apellidoMaterno; }
    public void setApellidoMaterno(String apellidoMaterno) { this.apellidoMaterno = apellidoMaterno; }

    public String getApellidoPaterno() { return apellidoPaterno; }
    public void setApellidoPaterno(String apellidoPaterno) { this.apellidoPaterno = apellidoPaterno; }

    public int getEdad() { return edad; }
    public void setEdad(int edad) { this.edad = edad; }

    public String getCurso() { return curso; }
    public void setCurso(String curso) { this.curso = curso; }

    public String getCelular() { return celular; }
    public void setCelular(String celular) { this.celular = celular; }

    public String getNombrePadre() { return nombrePadre; }
    public void setNombrePadre(String nombrePadre) { this.nombrePadre = nombrePadre; }

    public String getApellidoPadre() { return apellidoPadre; }
    public void setApellidoPadre(String apellidoPadre) { this.apellidoPadre = apellidoPadre; }

    public String getNombreMadre() { return nombreMadre; }
    public void setNombreMadre(String nombreMadre) { this.nombreMadre = nombreMadre; }

    public String getApellidoMadre() { return apellidoMadre; }
    public void setApellidoMadre(String apellidoMadre) { this.apellidoMadre = apellidoMadre; }

    public String getCelularPadre() { return celularPadre; }
    public void setCelularPadre(String celularPadre) { this.celularPadre = celularPadre; }

    public String getCelularMadre() { return celularMadre; }
    public void setCelularMadre(String celularMadre) { this.celularMadre = celularMadre; }
}
